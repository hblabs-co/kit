package og

import (
	"errors"
	"fmt"
	"net/http"
	"strconv"

	"github.com/hblabs-co/kit/core/constants"
	"github.com/hblabs-co/kit/core/log"
)

// pngContentType is the MIME type emitted for rendered cards. Content
// is content-addressed by Generator.Key, so the URL changes whenever
// the bytes change — that's what makes immutable caching safe here.
const pngContentType = "image/png"

// ogImmutableMaxAgeSeconds = 1 year, the upper bound recommended for
// `immutable` assets. Cards are content-addressed, so any change to
// the underlying Card produces a different URL — refetch is automatic.
const ogImmutableMaxAgeSeconds = 365 * 24 * 60 * 60

// HandlerOptions configures NewHandler.
type HandlerOptions struct {
	Generator *Generator
	Storage   Storage

	// Resolver maps an http.Request to the Card it represents.
	// Returning (_, false) makes the handler reply 404 — use that
	// for unknown locales, missing pages, or paths that don't match
	// the expected scheme. The Resolver is the only thing the
	// handler needs from outside, so a service can use any URL
	// scheme it likes (lang/page paths, opaque hashes, query
	// params) by writing one function.
	Resolver func(*http.Request) (Card, bool)
}

// NewHandler returns the cache-aside HTTP handler:
//
//  1. Resolve the request to a Card.
//  2. Hash the Card to a key.
//  3. Try Storage.Get(key) — hit serves the bytes.
//  4. Miss → Generator.Render(card) → Storage.PutIfAbsent →
//     serve the freshly-rendered bytes.
//
// On a transient storage failure (anything other than ErrNotFound),
// the handler returns 500 rather than rendering blind — re-rendering
// on every request during an outage hides the underlying problem and
// burns CPU. PutIfAbsent failures after a successful render are
// logged as warnings and the response still goes out, so a flapping
// storage layer doesn't break user-visible OG previews.
func NewHandler(opts HandlerOptions) http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if opts.Resolver == nil {
			log.ErrorContext(r.Context(), "og: handler has no resolver configured")
			http.Error(w, "Internal Server Error", http.StatusInternalServerError)
			return
		}
		card, ok := opts.Resolver(r)
		if !ok {
			http.NotFound(w, r)
			return
		}
		key := opts.Generator.Key(card)
		ctx := r.Context()

		if body, ctype, err := opts.Storage.Get(ctx, key); err == nil {
			serveImage(w, body, ctype)
			return
		} else if !errors.Is(err, ErrNotFound) {
			log.ErrorContext(ctx, "og: storage get failed",
				"err", err, "key", key)
			http.Error(w, "Internal Server Error", http.StatusInternalServerError)
			return
		}

		body, err := opts.Generator.Render(card)
		if err != nil {
			log.ErrorContext(ctx, "og: render failed",
				"err", err, "title", card.Title, "lang", card.Lang)
			http.Error(w, "Internal Server Error", http.StatusInternalServerError)
			return
		}
		if err := opts.Storage.PutIfAbsent(ctx, key, body, pngContentType); err != nil {
			log.WarnContext(ctx, "og: storage put failed (serving generated bytes anyway)",
				"err", err, "key", key)
		}
		serveImage(w, body, pngContentType)
	})
}

// serveImage writes body with the appropriate headers.
func serveImage(w http.ResponseWriter, body []byte, contentType string) {
	if contentType == "" {
		contentType = pngContentType
	}
	w.Header().Set(constants.HeaderContentType, contentType)
	w.Header().Set(constants.HeaderCacheControl, fmt.Sprintf("public, max-age=%d, immutable", ogImmutableMaxAgeSeconds))
	w.Header().Set(constants.HeaderContentLength, strconv.Itoa(len(body)))
	_, _ = w.Write(body)
}
